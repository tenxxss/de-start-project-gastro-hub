BEGIN;

-- Шаг 1. Блокируем строки заведений, у которых есть капучино.
-- FOR UPDATE ставит блокировку на уровне строк, а не таблицы:
-- можно и читать, и менять, потому что их строки не заблокированы.
-- Блокировку таблицы целиком не используем, она закрыла бы
-- доступ к меню заведений, где цены не меняются.
-- ORDER BY по uuid гарантирует одинаковый порядок захвата блокировок
-- у всех параллельных транзакций, так что взаимных блокировок не будет.
SELECT restaurant_uuid
FROM cafe.restaurants
WHERE type = 'coffee_shop'
  AND menu #> '{Кофе,Капучино}' IS NOT NULL
ORDER BY restaurant_uuid
FOR UPDATE;

-- Шаг 2. Поднимаем цену капучино на 20%.
-- jsonb_set меняет только одно значение внутри меню, остальное
-- меню остаётся как было.
UPDATE cafe.restaurants
SET menu = jsonb_set(
        menu,
        '{Кофе,Капучино}',
        to_jsonb(ROUND((menu #>> '{Кофе,Капучино}')::numeric * 1.2, 2))
    )
WHERE type = 'coffee_shop'
  AND menu #> '{Кофе,Капучино}' IS NOT NULL;
COMMIT;
